interface ClassSpecInput {
  id: ClassId;
  archetype: ArchetypeId | 'novice';
  isHidden?: boolean;
  isRangedCombat?: boolean;
  name: string;
  title: string;
  summary: string;
  bodyColor: string;
  bodyHighlight: string;
  cloakColor: string;
  helmColor: string;
  accentColor: string;
  hairColor?: string;
  weaponKind: WeaponKind;
  critDisabled?: boolean;
  baseHp: number;
  baseMp: number;
  baseAtk: number;
  baseDef: number;
  baseSpeed: number;
  baseCrit: number;
  baseCritDmg: number;
  baseAttackSpeed: number;
  baseMpRegen: number;
  hpPerLv: number;
  mpPerLv: number;
  atkPerLv: number;
  defPerLv: number;
  speedPerLv: number;
  basicAttackName: string;
  basicAttackIcon: string;
  basicCooldown: number;
  unlockHint?: string;
  skills: [SkillMeta, SkillMeta, SkillMeta, SkillMeta];
}

function makeClassDef(spec: ClassSpecInput): ClassDef {
  return {
    ...spec,
    branch: spec.archetype,
    skillQ: spec.skills[0],
    skillE: spec.skills[1],
  };
}

function skill(
  slot: SkillSlotIndex,
  key: 'Q' | 'E' | 'C' | 'V',
  name: string,
  icon: string,
  desc: string,
  mpCost: number,
  cooldown: number,
  pattern: SkillMeta['pattern'],
  powerMult: number,
  range: number,
  extra: Partial<Omit<SkillMeta, 'slot' | 'key' | 'name' | 'icon' | 'desc' | 'mpCost' | 'cooldown' | 'pattern' | 'powerMult' | 'range'>> = {}
): SkillMeta {
  return {
    slot,
    key,
    name,
    icon,
    desc,
    mpCost,
    cooldown,
    pattern,
    powerMult,
    range,
    ...extra,
  };
}

